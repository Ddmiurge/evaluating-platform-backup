package maclaw

// promptfoo_remote_dep.go — U6 · remote-generation capability guardrail.
//
// # The silent failure this file exists to prevent
//
// promptfoo's remote-testcase plugins are wired as:
//
//	if (neverGenerateRemote()) {
//	    logger.error(getRemoteGenerationExplicitlyDisabledError(`${key} plugin`));
//	    return [];              // no throw, no abort, exit code still 0
//	}
//
// (`node_modules/promptfoo/dist/src/index.js:16099-16133`, `createRemotePlugin`).
// The engine runs fail-closed (`PROMPTFOO_DISABLE_REMOTE_GENERATION=1`,
// asserted at startup in promptfoo_engine/src/env.ts), so that branch is ALWAYS
// taken for a remote-dependent plugin. The consequence is the worst failure
// shape in this system: the run succeeds, the report is produced, and the
// plugin's coverage is silently 0. The user sees "evaluation finished" and has
// no way to learn that a capability they selected was never exercised.
//
// U6 does not change any generation logic. It converts that silence into three
// explicit surfaces:
//
//  1. Catalog metadata — every entry carries `requires_remote_generation`.
//  2. Pre-flight rejection — a request naming a gated plugin/strategy fails
//     with `plugin_requires_remote_generation` / `strategy_requires_remote_generation`
//     instead of running 0 cases.
//  3. Frontend greying — the selector disables the entry and states why.
//
// # Single source of truth
//
// The mapping table is NOT hand-maintained. It is generated by
// scripts/gen_remote_dep.mjs into testdata/promptfoo_remote_dep.json by
// evaluating promptfoo's own tables at runtime, and embedded below.
//
// Why runtime evaluation rather than reading the source: REMOTE_ONLY_PLUGIN_IDS
// is assembled from 26 literals plus 8 `...spread` expressions referencing other
// tables. Counting source lines yields 26, not 93 — a 67-entry undercount that
// would have marked most real remote-only plugins as local-only.
//
// # Update procedure (after any promptfoo upgrade)
//
//	cd evaluating_platform/promptfoo_engine && npm ci
//	cd .. && node scripts/gen_remote_dep.mjs
//	cd .. && go test ./internal/maclaw/ -run TestPromptfooRemoteDep
//
// TestPromptfooRemoteDepMappingMatchesPromptfoo re-derives the intersection and
// fails if the committed table drifted from the installed promptfoo.

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// remoteDepTable is the on-disk shape of testdata/promptfoo_remote_dep.json.
// Field names mirror the JSON tags.
type remoteDepTable struct {
	Comment                  string                 `json:"_comment"`
	PromptfooVersion         string                 `json:"promptfoo_version"`
	PromptfooTablesChunk     string                 `json:"promptfoo_tables_chunk"`
	PromptfooRuntimeTotals   remoteDepRuntimeTotals `json:"promptfoo_runtime_totals"`
	PlatformCatalogTotals    remoteDepCatalogTotals `json:"platform_catalog_totals"`
	RemoteOnlyPluginIDs      []string               `json:"remote_only_plugin_ids"`
	UnalignedProviderHarmIDs []string               `json:"unaligned_provider_harm_plugin_ids"`
	BiasPluginIDs            []string               `json:"bias_plugin_ids"`
	CatalogMarkedPlugins     map[string]string      `json:"catalog_marked_plugins"`
	RemoteGatedStrategies    map[string]string      `json:"remote_gated_strategies"`
}

type remoteDepRuntimeTotals struct {
	RemoteOnlyPluginIDs          int `json:"remote_only_plugin_ids"`
	UnalignedProviderHarmPlugins int `json:"unaligned_provider_harm_plugins"`
	BiasPlugins                  int `json:"bias_plugins"`
}

type remoteDepCatalogTotals struct {
	Plugins   int `json:"plugins"`
	Marked    int `json:"marked"`
	LocalOnly int `json:"local_only"`
}

//go:embed testdata/promptfoo_remote_dep.json
var remoteDepTableJSON []byte

// Remote generation dependency sources, as recorded per plugin id. The
// attribution is exclusive (a plugin has exactly one source) so the three
// groups partition the marked set and the counts stay auditable.
const (
	RemoteDepSourceRemoteOnly            = "remote_only"
	RemoteDepSourceUnalignedProviderHarm = "unaligned_provider_harm"
	RemoteDepSourceBias                  = "bias"
)

// Error codes surfaced to the browser and stored on the run record. They are
// part of the API contract: the frontend maps them to a readable message, and
// operators grep for them when a run fails.
const (
	// EngineErrPluginRequiresRemoteGeneration means the request named at least
	// one plugin whose attack cases promptfoo can only fetch from its remote
	// generation service, which is fail-closed disabled in this deployment.
	EngineErrPluginRequiresRemoteGeneration = "plugin_requires_remote_generation"
	// EngineErrStrategyRequiresRemoteGeneration is the same guard for attack
	// strategies (best-of-n / likert / citation / composite throw inside
	// promptfoo rather than returning [], but only once the run is underway —
	// the pre-flight check moves that failure to before the run starts).
	EngineErrStrategyRequiresRemoteGeneration = "strategy_requires_remote_generation"
)

// RemoteGenerationUnavailableMessage is the user-facing explanation shown
// wherever a gated capability is greyed out or a request is rejected. It names
// the actual constraint (remote generation is fail-closed by policy) instead of
// implying the capability does not exist — the whole point of U6 is that users
// can see "this exists but is blocked here", not "the platform lacks it".
const RemoteGenerationUnavailableMessage = "需远程生成 · 当前环境已屏蔽（平台强制关闭 promptfoo 远程生成以防数据外泄）"

// remoteDepTableData is the parsed mapping table. Parsed once at init; a
// malformed table is a programming error in the generator, not a runtime
// condition, so init panics rather than degrading into a silently-empty guard.
var remoteDepTableData = mustParseRemoteDepTable()

func mustParseRemoteDepTable() remoteDepTable {
	var table remoteDepTable
	if err := json.Unmarshal(remoteDepTableJSON, &table); err != nil {
		panic(fmt.Sprintf("maclaw: embedded promptfoo_remote_dep.json is malformed: %v", err))
	}
	if len(table.CatalogMarkedPlugins) == 0 {
		panic("maclaw: embedded promptfoo_remote_dep.json marks zero plugins; the guardrail would be a no-op")
	}
	return table
}

// PluginRequiresRemoteGeneration reports whether the plugin's attack cases can
// only be produced by promptfoo's remote generation service.
//
// Ids outside the platform catalog return false: an unknown id is not known to
// be gated, and inventing a rejection here would break the existing "unknown
// plugin degrades to defaults" contract (U2/T2.2).
func PluginRequiresRemoteGeneration(pluginID string) bool {
	_, ok := remoteDepTableData.CatalogMarkedPlugins[strings.TrimSpace(pluginID)]
	return ok
}

// PluginRemoteDepSource returns the upstream table the plugin was matched
// against, or "" when the plugin is not gated.
func PluginRemoteDepSource(pluginID string) string {
	return remoteDepTableData.CatalogMarkedPlugins[strings.TrimSpace(pluginID)]
}

// StrategyRequiresRemoteGeneration reports whether the attack strategy is gated
// on remote generation in promptfoo. These throw inside the library rather than
// returning [], but only once the run is underway — so pre-flight rejection is
// what converts a mid-run crash into an actionable error.
func StrategyRequiresRemoteGeneration(strategyID string) bool {
	_, ok := remoteDepTableData.RemoteGatedStrategies[strings.TrimSpace(strategyID)]
	return ok
}

// PromptfooRemoteDepStrategyID maps a platform strategy id to the promptfoo
// native id it corresponds to (the two vocabularies differ for 3 of the 4:
// `likert` -> `jailbreak:likert`, `singleTurnComposite` ->
// `jailbreak:composite`). Returns "" when the strategy is not gated.
func PromptfooRemoteDepStrategyID(strategyID string) string {
	return remoteDepTableData.RemoteGatedStrategies[strings.TrimSpace(strategyID)]
}

// RemoteGenerationGatedPluginIDs returns the sorted ids of every catalog plugin
// that requires remote generation.
func RemoteGenerationGatedPluginIDs() []string {
	ids := make([]string, 0, len(remoteDepTableData.CatalogMarkedPlugins))
	for id := range remoteDepTableData.CatalogMarkedPlugins {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	return ids
}

// RemoteGenerationGatedStrategyIDs returns the sorted ids of every catalog
// strategy that requires remote generation.
func RemoteGenerationGatedStrategyIDs() []string {
	ids := make([]string, 0, len(remoteDepTableData.RemoteGatedStrategies))
	for id := range remoteDepTableData.RemoteGatedStrategies {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	return ids
}

// LocalOnlyPluginIDs returns the sorted catalog plugin ids that need no remote
// generation. These are the capabilities a run can fully exercise in this
// deployment.
func LocalOnlyPluginIDs() []string {
	ids := make([]string, 0, len(promptfooPluginCatalog))
	for _, entry := range promptfooPluginCatalog {
		if !PluginRequiresRemoteGeneration(entry.ID) {
			ids = append(ids, entry.ID)
		}
	}
	sort.Strings(ids)
	return ids
}

// PromptfooRemoteDepStats summarizes the guardrail for docs, tests and
// operator-facing endpoints.
type PromptfooRemoteDepStats struct {
	PromptfooVersion      string `json:"promptfoo_version"`
	CatalogPlugins        int    `json:"catalog_plugins"`
	RequiresRemote        int    `json:"requires_remote_generation"`
	LocalOnly             int    `json:"local_only"`
	RemoteOnlySource      int    `json:"remote_only_source"`
	UnalignedProviderHarm int    `json:"unaligned_provider_harm_source"`
	BiasSource            int    `json:"bias_source"`
	GatedStrategies       int    `json:"gated_strategies"`
	UnavailableMessage    string `json:"unavailable_message"`
}

// PromptfooRemoteDepStatsForCatalog computes the stats actually implied by the
// compiled-in plugin catalog, so a test can compare them against the committed
// table's self-reported totals.
func PromptfooRemoteDepStatsForCatalog() PromptfooRemoteDepStats {
	stats := PromptfooRemoteDepStats{
		PromptfooVersion:   remoteDepTableData.PromptfooVersion,
		CatalogPlugins:     len(promptfooPluginCatalog),
		GatedStrategies:    len(remoteDepTableData.RemoteGatedStrategies),
		UnavailableMessage: RemoteGenerationUnavailableMessage,
	}
	for _, entry := range promptfooPluginCatalog {
		switch PluginRemoteDepSource(entry.ID) {
		case RemoteDepSourceRemoteOnly:
			stats.RequiresRemote++
			stats.RemoteOnlySource++
		case RemoteDepSourceUnalignedProviderHarm:
			stats.RequiresRemote++
			stats.UnalignedProviderHarm++
		case RemoteDepSourceBias:
			stats.RequiresRemote++
			stats.BiasSource++
		default:
			stats.LocalOnly++
		}
	}
	return stats
}

// EngineRemoteDepGuardError reports which requested capabilities are gated on
// remote generation. It carries a machine-readable code for the API surface and
// a human-readable list for the UI.
type EngineRemoteDepGuardError struct {
	Code            string
	GatedPlugins    []string
	GatedStrategies []string
	LocalOnlyHint   []string
}

// Error implements error. The message names every blocked capability and, when
// there is at least one usable plugin, suggests what to pick instead — an error
// that only says "not allowed" would leave the user to guess.
func (e *EngineRemoteDepGuardError) Error() string {
	var parts []string
	if len(e.GatedPlugins) > 0 {
		parts = append(parts, "插件 "+strings.Join(e.GatedPlugins, ", "))
	}
	if len(e.GatedStrategies) > 0 {
		parts = append(parts, "策略 "+strings.Join(e.GatedStrategies, ", "))
	}
	msg := fmt.Sprintf("%s：%s", RemoteGenerationUnavailableMessage, strings.Join(parts, "；"))
	if hint := remoteGenerationHint(); hint != "" {
		msg += "。" + hint
	}
	return msg
}

// remoteGenerationHintRecommends are the plugins suggested when a run is
// refused. Ordered by how likely a user is to want them, NOT alphabetically:
// the local-only list is sorted, so a plain prefix slice would surface
// `beavertails, bias, contracts, …` and hide the names people actually reach
// for (`harmful`, `pii`).
//
// P2-1 removed `jailbreak` and `prompt-injection` from this list. Both are
// illegal PLUGIN ids (promptfoo's zod rejects them), so the message was
// recommending two options whose only possible outcome is a failed run — the
// most damaging form of the U6 hint, because it is the platform telling the
// user to pick something broken. `harmful` also has the highest fanout in the
// catalog (26), so it stays first for a second reason: it is the single
// highest-value local selection.
//
// `policy` is deliberately absent even though it is legal and local-only: it
// needs config.policy text the platform does not collect, so selecting it
// yields 0 cases and the run fails with native_generation_no_test_cases.
// Recommending it would trade one unexplained failure for another. The bar for
// this list is "selecting it produces a run that works", which is stricter
// than "promptfoo accepts it" — TestRemoteGenerationHintRecommendsAreLegal
// pins all three conditions (legal, local-only, not config-gated) so the list
// cannot drift back into recommending something that cannot complete.
var remoteGenerationHintRecommends = []string{"harmful", "pii", "bias", "contracts"}

// remoteGenerationHint renders the "try these instead" clause of the rejection
// message. It lists as many of the recommended plugins as are actually usable,
// then tops up with other local-only ids (alphabetically) so the suggestion is
// never empty when local plugins exist.
func remoteGenerationHint() string {
	available := make(map[string]bool, len(remoteDepTableData.CatalogMarkedPlugins))
	for id := range remoteDepTableData.CatalogMarkedPlugins {
		available[id] = true
	}
	local := LocalOnlyPluginIDs()
	if len(local) == 0 {
		return ""
	}

	picked := make([]string, 0, len(remoteGenerationHintRecommends))
	for _, id := range remoteGenerationHintRecommends {
		if !available[id] && containsString(local, id) {
			picked = append(picked, id)
		}
	}
	for _, id := range local {
		if len(picked) >= remoteGenerationHintMax {
			break
		}
		if !containsString(picked, id) {
			picked = append(picked, id)
		}
	}
	if len(picked) == 0 {
		return ""
	}
	if len(local) > len(picked) {
		return fmt.Sprintf("当前环境可完整评测的插件（共 %d 个）例如：%s 等",
			len(local), strings.Join(picked, "、"))
	}
	return fmt.Sprintf("当前环境可完整评测的插件为：%s",
		strings.Join(picked, "、"))
}

// remoteGenerationHintMax caps how many plugins the rejection message names, so
// a 29-item list never becomes an unreadable wall of text.
const remoteGenerationHintMax = 6

// containsString reports whether needle is present in haystack.
func containsString(haystack []string, needle string) bool {
	for _, item := range haystack {
		if item == needle {
			return true
		}
	}
	return false
}

// ValidateEngineRunRemoteGeneration is the U6 pre-flight guard. It rejects a
// run request that names any remote-generation-gated plugin or strategy, so the
// request fails fast with a readable code instead of producing a successful run
// with 0 cases for the gated capabilities.
//
// It is a pure predicate over the request: no I/O, no catalog mutation, no
// engine dispatch. Callers must invoke it before persisting or submitting
// anything, so a rejected request leaves no half-created run behind.
//
// Unknown ids pass (they are not known to be gated); duplicate ids are collapsed
// so the error message lists each capability once.
func ValidateEngineRunRemoteGeneration(plugins, strategies []EngineCapabilityRef) error {
	gatedPlugins := gatedIDs(plugins, PluginRequiresRemoteGeneration)
	gatedStrategies := gatedIDs(strategies, StrategyRequiresRemoteGeneration)
	if len(gatedPlugins) == 0 && len(gatedStrategies) == 0 {
		return nil
	}
	code := EngineErrPluginRequiresRemoteGeneration
	if len(gatedPlugins) == 0 {
		code = EngineErrStrategyRequiresRemoteGeneration
	}
	return &EngineRemoteDepGuardError{
		Code:            code,
		GatedPlugins:    gatedPlugins,
		GatedStrategies: gatedStrategies,
		LocalOnlyHint:   LocalOnlyPluginIDs(),
	}
}

// gatedIDs returns the sorted, de-duplicated ids of refs matching pred.
func gatedIDs(refs []EngineCapabilityRef, pred func(string) bool) []string {
	seen := make(map[string]bool, len(refs))
	out := make([]string, 0, len(refs))
	for _, ref := range refs {
		id := strings.TrimSpace(ref.ID)
		if id == "" || seen[id] || !pred(id) {
			continue
		}
		seen[id] = true
		out = append(out, id)
	}
	sort.Strings(out)
	return out
}
