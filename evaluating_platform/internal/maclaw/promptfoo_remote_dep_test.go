package maclaw

// promptfoo_remote_dep_test.go — U6 guardrail integrity assertions.
//
// # What this file protects
//
// The U6 guardrail (promptfoo_remote_dep.go) makes a strong claim: 90 of the
// 116 catalog plugins cannot be exercised in this deployment because promptfoo
// can only fetch their attack cases from a remote generation service that is
// fail-closed disabled here; the remaining 26 are fully local.
//
// (P2-1: the catalog was 119 / 29 before the three illegal plugin ids —
// `prompt-injection`, `jailbreak`, `security-exploit` — were withdrawn. All
// three sat in the "local" side, so the local count fell 29 → 26 while the
// marked count stayed 90. See promptfoo_plugin_legality.go for the verdict
// table and retiredPluginCatalog for where each capability moved.)
//
// That claim is only worth anything if it stays true. It is derived from an
// embedded table (testdata/promptfoo_remote_dep.json) that was generated by
// scripts/gen_remote_dep.mjs against a specific promptfoo version. Two ways it
// can rot:
//
//  1. promptfoo is upgraded and the remote-dependency set changes → our table
//     is stale, and the platform keeps greying plugins that are now perfectly
//     usable (or worse, allows plugins that now silently produce 0 cases — the
//     exact failure U6 exists to prevent).
//  2. somebody hand-edits the catalog or the table → the marks and the upstream
//     reality drift apart with nothing noticing.
//
// The assertions below close both holes. They are cheap (no network, no Node
// toolchain) and they run in the ordinary `go test ./...` CI job.
//
// # A note on scope
//
// These tests verify INTERNAL CONSISTENCY plus the declared provenance. They
// cannot re-derive the table from an installed promptfoo, because the backend
// CI job does not install promptfoo_engine's node_modules. The provenance
// binding is therefore established by TestRemoteDepProvenanceMatchesInstalled
// Promptfoo (declared version == the version pinned in promptfoo_engine/
// package.json == the version present in the committed package-lock.json), and
// the value-level re-derivation is the generator's job:
//
//	node scripts/gen_remote_dep.mjs && git diff --exit-code \
//	  internal/maclaw/testdata/promptfoo_remote_dep.json
//
// That command is documented in promptfoo_remote_dep.go and must be run after
// every promptfoo upgrade (U7 Step 0).

import (
	"encoding/json"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"testing"
)

// promptfooRemoteDepPath resolves the committed mapping table relative to this
// test file, so the assertions work from any `go test` working directory.
func promptfooRemoteDepPath(t *testing.T) string {
	t.Helper()
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatalf("runtime.Caller failed to resolve the test file path")
	}
	return filepath.Join(filepath.Dir(thisFile), "testdata", "promptfoo_remote_dep.json")
}

// readRemoteDepTable parses the committed table fresh (not via the embedded
// copy) so these tests inspect the file on disk, which is what a reviewer edits.
func readRemoteDepTable(t *testing.T) remoteDepTable {
	t.Helper()
	raw, err := os.ReadFile(promptfooRemoteDepPath(t))
	if err != nil {
		t.Fatalf("read mapping table: %v", err)
	}
	var table remoteDepTable
	if err := json.Unmarshal(raw, &table); err != nil {
		t.Fatalf("parse mapping table %s: %v", promptfooRemoteDepPath(t), err)
	}
	return table
}

// TestPromptfooRemoteDepMappingMatchesPromptfoo is the core anti-drift anchor:
// the 29 ids the platform advertises as locally usable must be EXACTLY the
// complement of the 90 marked ids among the 119 catalog entries. If either side
// moves without the other, this fails and names the disagreement.
func TestPromptfooRemoteDepMappingMatchesPromptfoo(t *testing.T) {
	table := readRemoteDepTable(t)

	catalogIDs := PromptfooEngineSupportedPluginIDs()
	if len(catalogIDs) != len(promptfooPluginCatalog) {
		t.Fatalf("catalog id count = %d, want %d", len(catalogIDs), len(promptfooPluginCatalog))
	}

	inCatalog := make(map[string]bool, len(catalogIDs))
	for _, id := range catalogIDs {
		inCatalog[id] = true
	}

	// Partition the catalog using the table's marks.
	marked := make([]string, 0, len(catalogIDs))
	local := make([]string, 0, len(catalogIDs))
	for _, id := range catalogIDs {
		if _, ok := table.CatalogMarkedPlugins[id]; ok {
			marked = append(marked, id)
		} else {
			local = append(local, id)
		}
	}
	sort.Strings(marked)
	sort.Strings(local)

	// 1. Every mark must name a plugin that actually exists in the catalog.
	//    A typo or a leftover from an older catalog would otherwise grey out
	//    nothing while inflating the "blocked" count in error messages.
	for id := range table.CatalogMarkedPlugins {
		if !inCatalog[id] {
			t.Errorf("mapping table marks %q but the catalog has no such plugin; "+
				"regenerate with `node scripts/gen_remote_dep.mjs`", id)
		}
	}

	// 2. The declared totals must match what the table actually contains.
	if got, want := len(marked), table.PlatformCatalogTotals.Marked; got != want {
		t.Errorf("marked plugins = %d, table declares %d (table is stale — regenerate)", got, want)
	}
	if got, want := len(local), table.PlatformCatalogTotals.LocalOnly; got != want {
		t.Errorf("local-only plugins = %d, table declares %d (table is stale — regenerate)", got, want)
	}
	if got, want := len(catalogIDs), table.PlatformCatalogTotals.Plugins; got != want {
		t.Errorf("catalog plugins = %d, table declares %d (table is stale — regenerate)", got, want)
	}

	// 3. marked ∪ local == catalog, and they are disjoint. This is the partition
	//    invariant: a plugin cannot be both usable and blocked, and none may fall
	//    through unclassified.
	if len(marked)+len(local) != len(catalogIDs) {
		t.Errorf("partition broken: %d marked + %d local != %d catalog entries",
			len(marked), len(local), len(catalogIDs))
	}

	// 4. The same partition must hold through the exported predicates, which is
	//    what the handler, the bridge and the frontend actually call.
	for _, id := range marked {
		if !PluginRequiresRemoteGeneration(id) {
			t.Errorf("PluginRequiresRemoteGeneration(%q) = false, but the table marks it", id)
		}
	}
	for _, id := range local {
		if PluginRequiresRemoteGeneration(id) {
			t.Errorf("PluginRequiresRemoteGeneration(%q) = true, but the table does not mark it", id)
		}
	}

	// 5. The headline number, pinned so a silent change to the platform's
	//    usable surface cannot land unnoticed. This is the figure quoted in
	//    audit-2026-10-09/14 §3.2 and in docs/architecture.
	//
	//    P2-1 moved `local` 29 → 26 (three illegal ids withdrawn; see the file
	//    header). `marked` is unchanged: none of the three was remote-gated.
	const wantMarked, wantLocal = 90, 26
	if len(marked) != wantMarked || len(local) != wantLocal {
		t.Errorf("usable surface changed: %d marked / %d local, want %d / %d — "+
			"if this is an intentional promptfoo upgrade, regenerate the table and update "+
			"audit-2026-10-09/14 §3.2 plus docs/architecture in the same commit",
			len(marked), len(local), wantMarked, wantLocal)
	}
}

// TestPromptfooRemoteDepSourceAttributionIsPartitioned verifies each marked id
// is attributed to exactly one upstream table, and that the per-source counts
// match the three runtime totals the table records. Keeps the "65 / 21 / 4"
// breakdown auditable rather than a comment that can rot.
func TestPromptfooRemoteDepSourceAttributionIsPartitioned(t *testing.T) {
	table := readRemoteDepTable(t)

	bySource := map[string]int{}
	for id, source := range table.CatalogMarkedPlugins {
		switch source {
		case RemoteDepSourceRemoteOnly, RemoteDepSourceUnalignedProviderHarm, RemoteDepSourceBias:
			bySource[source]++
		default:
			t.Errorf("plugin %q has unknown remote-dep source %q", id, source)
		}
		if got := PluginRemoteDepSource(id); got != source {
			t.Errorf("PluginRemoteDepSource(%q) = %q, table says %q", id, got, source)
		}
	}

	// Each marked id must appear in exactly one of the three upstream lists, and
	// the lists' intersection with the catalog must reproduce the attribution.
	upstream := map[string]map[string]bool{
		RemoteDepSourceRemoteOnly:            toIDSet(table.RemoteOnlyPluginIDs),
		RemoteDepSourceUnalignedProviderHarm: toIDSet(table.UnalignedProviderHarmIDs),
		RemoteDepSourceBias:                  toIDSet(table.BiasPluginIDs),
	}
	for id, source := range table.CatalogMarkedPlugins {
		hits := 0
		for _, set := range upstream {
			if set[id] {
				hits++
			}
		}
		if hits != 1 {
			t.Errorf("plugin %q appears in %d of the 3 upstream lists (want exactly 1, attributed to %q)", id, hits, source)
		}
	}

	// The per-source hit counts against the catalog, pinned from the runtime
	// evaluation recorded in audit-2026-10-09/14 §3.2.
	for source, want := range map[string]int{
		RemoteDepSourceRemoteOnly:            65,
		RemoteDepSourceUnalignedProviderHarm: 21,
		RemoteDepSourceBias:                  4,
	} {
		if got := bySource[source]; got != want {
			t.Errorf("catalog hits for %q = %d, want %d (regenerate the table)", source, got, want)
		}
	}

	// The upstream runtime totals must agree with the recorded list lengths, so a
	// truncated or hand-edited list is caught even if the catalog intersection
	// happens to be unaffected.
	for name, pair := range map[string]struct{ got, want int }{
		"REMOTE_ONLY_PLUGIN_IDS":          {len(table.RemoteOnlyPluginIDs), table.PromptfooRuntimeTotals.RemoteOnlyPluginIDs},
		"UNALIGNED_PROVIDER_HARM_PLUGINS": {len(table.UnalignedProviderHarmIDs), table.PromptfooRuntimeTotals.UnalignedProviderHarmPlugins},
		"BIAS_PLUGINS":                    {len(table.BiasPluginIDs), table.PromptfooRuntimeTotals.BiasPlugins},
	} {
		if pair.got != pair.want {
			t.Errorf("%s list has %d entries, table declares %d", name, pair.got, pair.want)
		}
	}
}

// TestRemoteDepProvenanceMatchesInstalledPromptfoo binds the table to the
// promptfoo build the platform actually ships. Without this, upgrading promptfoo
// in promptfoo_engine/package.json would leave the mapping table silently
// describing a version nobody runs.
//
// The backend CI job has no node_modules, so this asserts against the two
// version declarations that ARE committed: package.json and package-lock.json.
func TestRemoteDepProvenanceMatchesInstalledPromptfoo(t *testing.T) {
	table := readRemoteDepTable(t)

	repoRoot := filepath.Join(filepath.Dir(promptfooRemoteDepPath(t)), "..", "..", "..")
	engineDir := filepath.Join(repoRoot, "promptfoo_engine")

	raw, err := os.ReadFile(filepath.Join(engineDir, "package.json"))
	if err != nil {
		t.Fatalf("read promptfoo_engine/package.json: %v", err)
	}
	var pkg struct {
		Dependencies struct {
			Promptfoo string `json:"promptfoo"`
		} `json:"dependencies"`
	}
	if err := json.Unmarshal(raw, &pkg); err != nil {
		t.Fatalf("parse promptfoo_engine/package.json: %v", err)
	}
	if pkg.Dependencies.Promptfoo == "" {
		t.Fatalf("promptfoo_engine/package.json does not pin a promptfoo dependency")
	}
	if want := strings.TrimPrefix(pkg.Dependencies.Promptfoo, "^"); table.PromptfooVersion != want {
		t.Errorf("mapping table was generated against promptfoo %q but promptfoo_engine/package.json pins %q. "+
			"After upgrading promptfoo, run `node scripts/gen_remote_dep.mjs` and commit the regenerated table.",
			table.PromptfooVersion, want)
	}

	// The lockfile is the version that is actually installed in CI/dev. A range
	// in package.json resolved to something else means the table describes a
	// build we do not run.
	lockPath := filepath.Join(engineDir, "package-lock.json")
	lockRaw, err := os.ReadFile(lockPath)
	if err != nil {
		t.Fatalf("read promptfoo_engine/package-lock.json: %v", err)
	}
	var lock struct {
		Packages map[string]struct {
			Version string `json:"version"`
		} `json:"packages"`
	}
	if err := json.Unmarshal(lockRaw, &lock); err != nil {
		t.Fatalf("parse package-lock.json: %v", err)
	}
	if got := lock.Packages["node_modules/promptfoo"].Version; got != "" && got != table.PromptfooVersion {
		t.Errorf("package-lock.json installs promptfoo %q but the mapping table describes %q. "+
			"Run `node scripts/gen_remote_dep.mjs` and commit the result.", got, table.PromptfooVersion)
	}
}

// TestPromptfooRemoteDepStrategyGate pins the strategy-side mapping, including
// the platform→promptfoo id translation for the entries whose vocabularies
// differ. A wrong translation would make the error message name a strategy the
// engine cannot recognise.
func TestPromptfooRemoteDepStrategyGate(t *testing.T) {
	table := readRemoteDepTable(t)

	strategyIDs := PromptfooEngineSupportedStrategyIDs()
	inCatalog := toIDSet(strategyIDs)

	for platformID, nativeID := range table.RemoteGatedStrategies {
		// A gated id must be either OFFERED, or a platform id the platform can
		// still express. P2-2: `jailbreak` is gated precisely because it is no
		// longer offered — it is the deprecated alias of the gated
		// `iterative:meta`, and a stored request or a direct API call can still
		// name it. Requiring catalogue membership would have forced leaving it
		// un-gated, which is how it failed mid-run in the first place.
		_, translated := strategyCatalogData.PlatformToNativeMap[platformID]
		if !inCatalog[platformID] && !translated {
			t.Errorf("gated strategy %q is neither offered nor a known platform→native translation; the mapping is stale", platformID)
		}
		if !StrategyRequiresRemoteGeneration(platformID) {
			t.Errorf("StrategyRequiresRemoteGeneration(%q) = false, but the table gates it", platformID)
		}
		if got := PromptfooRemoteDepStrategyID(platformID); got != nativeID {
			t.Errorf("PromptfooRemoteDepStrategyID(%q) = %q, table says %q", platformID, got, nativeID)
		}
		if nativeID == "" {
			t.Errorf("gated strategy %q has an empty promptfoo id", platformID)
		}
	}
	for _, id := range strategyIDs {
		if _, gated := table.RemoteGatedStrategies[id]; gated {
			continue
		}
		if StrategyRequiresRemoteGeneration(id) {
			t.Errorf("StrategyRequiresRemoteGeneration(%q) = true, but the table does not gate it", id)
		}
	}

	// Pinned: six strategies are gated. Was four until P2-2; the two additions
	// (`iterative:meta`, and `jailbreak` as its deprecated alias) were offered
	// and failed mid-run because the gate was a hand-kept list that never learned
	// about them.
	if got, want := len(table.RemoteGatedStrategies), 6; got != want {
		t.Errorf("gated strategies = %d, want %d", got, want)
	}
	for platformID, nativeID := range map[string]string{
		"bestOfN":             "best-of-n",
		"likert":              "jailbreak:likert",
		"citation":            "citation",
		"singleTurnComposite": "jailbreak:composite",
		"iterative:meta":      "jailbreak:meta",
		"jailbreak":           "jailbreak",
	} {
		if table.RemoteGatedStrategies[platformID] != nativeID {
			t.Errorf("strategy %q maps to %q, want %q", platformID, table.RemoteGatedStrategies[platformID], nativeID)
		}
	}
}

// TestEveryOfferedRemoteRequiredStrategyIsGated is the completeness guard the
// P2-2 defect needed: the gate table is derived from the MEASURED
// `remote_required` verdict, so any strategy the platform offers whose native
// implementation refuses to run must appear in it.
//
// Counter-proof: drop `iterative:meta` from remote_gated_strategies → this goes
// red and names it. Before this test, the gate was a hand-written four-entry map
// and nothing compared it against what promptfoo actually requires.
func TestEveryOfferedRemoteRequiredStrategyIsGated(t *testing.T) {
	table := readRemoteDepTable(t)

	platformToNative := strategyCatalogData.PlatformToNativeMap
	checked := 0
	for _, platformID := range PromptfooEngineSupportedStrategyIDs() {
		nativeID := StrategyNativeID(platformID)
		row, ok := NativeStrategyByID(nativeID)
		if !ok {
			continue
		}
		if !row.RemoteRequired {
			continue
		}
		checked++
		gatedNative, gated := table.RemoteGatedStrategies[platformID]
		if !gated {
			t.Errorf("offered strategy %q reaches promptfoo's remote-required implementation %q "+
				"but is not gated; selecting it fails the run instead of being refused at submit. "+
				"Regenerate with `node scripts/gen_strategy_catalog.mjs && node scripts/gen_remote_dep.mjs`.",
				platformID, nativeID)
			continue
		}
		// The gate's translation must be the same one the rest of the platform
		// uses, or the error message would name a strategy the engine cannot
		// recognise.
		if want := platformToNative[platformID]; want != "" && want != gatedNative {
			t.Errorf("gated %q translates to %q but the strategy catalogue says %q",
				platformID, gatedNative, want)
		}
	}
	if checked == 0 {
		t.Fatal("no offered strategy is measured remote-required; the comparison is not exercising anything")
	}
}

// TestValidateEngineRunRemoteGenerationRejectsGatedCapabilities is the behaviour
// assertion behind the pre-flight guard: a request naming a gated capability is
// refused with a machine-readable code and a human-readable message, and a
// request naming only local capabilities is untouched.
//
// The counter-proof cases matter as much as the happy path: the guard must not
// become a blanket ban (unknown ids, duplicates, whitespace) or it would block
// valid evaluations.
func TestValidateEngineRunRemoteGenerationRejectsGatedCapabilities(t *testing.T) {
	refs := func(ids ...string) []EngineCapabilityRef {
		out := make([]EngineCapabilityRef, 0, len(ids))
		for _, id := range ids {
			out = append(out, EngineCapabilityRef{ID: id})
		}
		return out
	}

	t.Run("local only request passes", func(t *testing.T) {
		if err := ValidateEngineRunRemoteGeneration(refs("harmful", "pii"), refs("direct", "base64")); err != nil {
			t.Fatalf("local-only request rejected: %v", err)
		}
	})

	t.Run("empty request passes", func(t *testing.T) {
		if err := ValidateEngineRunRemoteGeneration(nil, nil); err != nil {
			t.Fatalf("empty request rejected: %v", err)
		}
	})

	t.Run("gated plugin is refused with a readable code", func(t *testing.T) {
		err := ValidateEngineRunRemoteGeneration(refs("harmful", "financial:hallucination"), nil)
		if err == nil {
			t.Fatal("gated plugin was accepted; the guardrail is not enforcing")
		}
		guard, ok := err.(*EngineRemoteDepGuardError)
		if !ok {
			t.Fatalf("error type = %T, want *EngineRemoteDepGuardError", err)
		}
		if guard.Code != EngineErrPluginRequiresRemoteGeneration {
			t.Errorf("code = %q, want %q", guard.Code, EngineErrPluginRequiresRemoteGeneration)
		}
		if len(guard.GatedPlugins) != 1 || guard.GatedPlugins[0] != "financial:hallucination" {
			t.Errorf("GatedPlugins = %v, want [financial:hallucination]", guard.GatedPlugins)
		}
		// The message must name the blocked capability and the reason, or the
		// user cannot act on it.
		for _, want := range []string{"financial:hallucination", RemoteGenerationUnavailableMessage} {
			if !strings.Contains(guard.Error(), want) {
				t.Errorf("error message %q does not mention %q", guard.Error(), want)
			}
		}
	})

	t.Run("gated strategy is refused with the strategy code", func(t *testing.T) {
		err := ValidateEngineRunRemoteGeneration(refs("harmful"), refs("citation"))
		guard, ok := err.(*EngineRemoteDepGuardError)
		if !ok {
			t.Fatalf("error = %v (%T), want *EngineRemoteDepGuardError", err, err)
		}
		if guard.Code != EngineErrStrategyRequiresRemoteGeneration {
			t.Errorf("code = %q, want %q", guard.Code, EngineErrStrategyRequiresRemoteGeneration)
		}
	})

	t.Run("duplicates and whitespace collapse to one entry", func(t *testing.T) {
		err := ValidateEngineRunRemoteGeneration(refs("financial:hallucination", " financial:hallucination "), nil)
		guard, ok := err.(*EngineRemoteDepGuardError)
		if !ok {
			t.Fatalf("error = %v, want guard error", err)
		}
		if len(guard.GatedPlugins) != 1 {
			t.Errorf("GatedPlugins = %v, want exactly 1 after dedup", guard.GatedPlugins)
		}
	})

	t.Run("unknown ids are not blocked", func(t *testing.T) {
		// Preserves the U2/T2.2 contract that an unknown plugin degrades to
		// defaults rather than being rejected.
		if err := ValidateEngineRunRemoteGeneration(refs("some:unknown", "xstest2"), refs("no-such-strategy")); err != nil {
			t.Fatalf("unknown ids rejected: %v", err)
		}
	})

	t.Run("local-only hint is offered so the error is actionable", func(t *testing.T) {
		err := ValidateEngineRunRemoteGeneration(refs("financial:hallucination"), nil)
		guard := err.(*EngineRemoteDepGuardError)
		if len(guard.LocalOnlyHint) != 26 {
			t.Errorf("LocalOnlyHint has %d entries, want 26", len(guard.LocalOnlyHint))
		}
		// P2-1: this used to require "jailbreak" — a plugin id promptfoo
		// rejects. The message was telling the user to pick something broken.
		for _, want := range []string{"harmful", "pii"} {
			if !strings.Contains(guard.Error(), want) {
				t.Errorf("error message offers no usable alternative (%q missing)", want)
			}
		}
		for _, banned := range IllegalPluginIDs() {
			if strings.Contains(guard.Error(), banned) {
				t.Errorf("error message recommends the withdrawn plugin id %q", banned)
			}
		}
	})
}

// TestRemoteGenerationHintRecommendsAreLegal pins the one property that makes
// the rejection hint worth having: every id it suggests must produce a run that
// actually works.
//
// Three conditions, and the third is the one that is easy to forget — a plugin
// can be legal AND local-only AND still yield 0 cases because the platform
// holds no config text for it (`policy`). Recommending it would swap one
// unexplained failure for another.
//
// Counter-proof: put `jailbreak` back in remoteGenerationHintRecommends → this
// test fails on legality; put `policy` in → it fails on config-gating.
func TestRemoteGenerationHintRecommendsAreLegal(t *testing.T) {
	if len(remoteGenerationHintRecommends) == 0 {
		t.Fatal("the rejection hint recommends nothing; the message loses its actionable half")
	}
	for _, id := range remoteGenerationHintRecommends {
		if !PluginIDIsLegal(id) {
			t.Errorf("hint recommends %q, which promptfoo rejects — selecting it fails the whole run", id)
		}
		if PluginRequiresRemoteGeneration(id) {
			t.Errorf("hint recommends %q, which is remote-gated — it would hit this same rejection", id)
		}
		if PluginRequiresConfig(id) {
			t.Errorf("hint recommends %q, which needs config the platform does not collect — it yields 0 cases", id)
		}
	}
}

// TestPromptfooRemoteDepSurfacesInCatalogAndEnginePayload verifies the flag
// actually reaches the three consumers, because a table that is correct but not
// plumbed through would grey nothing and reject nothing.
func TestPromptfooRemoteDepSurfacesInCatalogAndEnginePayload(t *testing.T) {
	// 1. Capability cards: present, marked, and still visible+enabled. The
	//    "not hidden" part is the requirement — a user must be able to see that
	//    the capability exists.
	//
	//    Scope: PromptfooPluginCatalogCards() returns BOTH plugins and strategies
	//    (119 + 30 = 149 cards), so the plugin-only figures must be counted over
	//    plugin SourceRefs, not over every card.
	marked, local := 0, 0
	var sampleLocal, sampleRemote string
	for _, card := range PromptfooPluginCatalogCards() {
		isPlugin := strings.HasPrefix(card.SourceRef, "promptfoo_plugin:")
		flag := card.SafeMetadata["requires_remote_generation"]
		if flag == "true" {
			if isPlugin {
				marked++
			}
			if card.SafeMetadata["unavailable_reason"] != RemoteGenerationUnavailableMessage {
				t.Errorf("%s is marked but carries no reason", card.SourceRef)
			}
			if !card.Enabled {
				t.Errorf("%s is marked unavailable yet Enabled=false; it must stay visible", card.SourceRef)
			}
			if isPlugin {
				sampleRemote = card.SourceRef
			}
			continue
		}
		if isPlugin {
			local++
			sampleLocal = card.SourceRef
		}
	}
	if marked != 90 || local != 26 {
		t.Errorf("plugin cards: %d marked / %d unmarked, want 90 / 26", marked, local)
	}
	// Spot-check one of each so a mis-wired SafeMetadata key cannot pass on
	// counts alone.
	if !strings.Contains(sampleRemote, ":") {
		t.Errorf("expected a namespaced gated card, got %q", sampleRemote)
	}
	if sampleLocal == "" {
		t.Error("no unmarked plugin card found")
	}

	// 2. EngineCatalog: the flag must reach the engine, since the engine's own
	//    gate reads it from there rather than keeping a second mapping table.
	catalog := PromptfooEngineCatalog()
	gatedPlugins, gatedStrategies := 0, 0
	for _, plugin := range catalog.Plugins {
		if plugin.RequiresRemoteGeneration {
			gatedPlugins++
			if plugin.UnavailableReason != RemoteGenerationUnavailableMessage {
				t.Errorf("engine catalog plugin %s is gated but carries no reason", plugin.ID)
			}
		}
	}
	for _, strategy := range catalog.Strategies {
		if !strategy.RequiresRemoteGeneration {
			continue
		}
		gatedStrategies++
		if strategy.PromptfooID == "" {
			t.Errorf("gated engine strategy %s carries no promptfoo id", strategy.ID)
		}
	}
	if gatedPlugins != 90 {
		t.Errorf("engine catalog gated plugins = %d, want 90", gatedPlugins)
	}
	// P2-2: 5, not 4. `iterative:meta` joined the gate; `jailbreak` is gated too
	// but is not in the engine catalogue, because it is no longer offered — the
	// engine catalogue carries what a request can name, and `jailbreak` is only
	// reachable through a stale request, which the BFF refuses first.
	if gatedStrategies != 5 {
		t.Errorf("engine catalog gated strategies = %d, want 5", gatedStrategies)
	}
}

